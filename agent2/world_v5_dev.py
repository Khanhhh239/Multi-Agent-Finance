def development_config(seed):
    if seed not in range(1001, 1021):
        raise ValueError('Development seeds must be 1001 through 1020')
    rng = np.random.default_rng(seed + 510_000)
    return {'seed': seed, 'rows': 200_000, 'fraud_rate': .004,
            'companies': int(rng.integers(30, 61)), 'money_scale': float(np.exp(rng.uniform(0, np.log(20)))),
            'difficulty_weights': rng.dirichlet(np.ones(3)).tolist(), 'calendar_seed': seed + 520_000,
            'data_origin': 'dữ liệu tổng hợp'}


def scale_money(tables, factor):
    """Scale raw currency before accounting constructs VAT and balanced journals.

    Monetary values use 1,000 VND precision, unit prices use 1 VND precision.
    Structural keys, quantities and labels are never scaled. Iterating table
    rows once avoids scaling shared employee dictionaries twice.
    """
    visited = set()
    for rows in tables.values():
        for row in rows:
            if id(row) in visited:
                continue
            visited.add(id(row))
            for key, value in list(row.items()):
                if key.endswith('_vnd') and value not in ('', None):
                    unit = 1 if key == 'unit_price_vnd' else 1000
                    scaled = round(float(value) * factor / unit) * unit
                    row[key] = max(unit, scaled) if float(value) > 0 else scaled
            if 'amount_scale' in row:
                row['amount_scale'] = float(row['amount_scale']) * factor


class WorldV5Development(WorldV4):
    def __init__(self, config):
        self.development = config
        super().__init__(n=config['rows'], rate=config['fraud_rate'], seed=config['seed'],
                         companies=config['companies'], difficulty_weights=tuple(config['difficulty_weights']))

    def make_masters(self, count):
        super().make_masters(count)
        rng = random.Random(self.development['calendar_seed'])
        for company in self.tables['companies']:
            # Calendar randomization is independent of labels and fraud placement.
            days = sorted(rng.sample(range(1, 29), 2)) if rng.random() < .15 else [rng.randint(1, 28)]
            if len(days) == 1 and rng.random() < .15:
                days = ['last']
            self.profile[company['company_id']]['pay_days'] = days
            company['pay_days'] = '|'.join(map(str, days))

    def open_case(self, scheme, cid, split=None):
        case = super().open_case(scheme, cid, split)
        # v4's case factory used fixed concealment shares independently of
        # WorldV3.difficulty_weights. Override the actual case-level draw.
        case['concealment'] = self.rng.choices(['L0', 'L1', 'L2'], self.development['difficulty_weights'])[0]
        return case

    def finalize(self):
        # Same placement sequence as Generator.finalize, with scaling BEFORE
        # invoice/VAT/journal construction, rather than rounding balanced books.
        self.inject_fraud()
        self.inject_normal_advances()
        self.inject_hard_negatives()
        self.rows.sort(key=lambda r: (r['posted_at'], r['transaction_id']))
        labels = {r['transaction_id']: r for r in self.truth}
        self.truth = [labels[r['transaction_id']] for r in self.rows]
        self.tables['transactions'] = self.rows
        self.tables['labels'] = self.truth
        self.tables['truth_cases'] = self.cases
        self.tables['splits'] = [dict(transaction_id=r['transaction_id'],
            split=next(s for s, (a, b) in WINDOWS.items() if a <= parse(r['posted_at']) < b)) for r in self.rows]
        scale_money(self.tables, self.development['money_scale'])
        # enrich_accounting reconstructs invoices and journal tables in full.
        self.tables['invoices'] = []
        return enrich_accounting(self.tables, self.seed)


def generate(config, directory):
    directory = Path(directory)
    if directory.exists() and any(directory.iterdir()):
        raise FileExistsError(f'Refusing to overwrite existing world: {directory}')
    world = WorldV5Development(config)
    tables = world.finalize()
    manifest = save_dataset(directory, tables, config['rows'], config['fraud_rate'], config['seed'], config['companies'])
    manifest.update(version='5.0-development', development=config, data_origin='dữ liệu tổng hợp')
    write_json(directory / 'manifest.json', manifest)
    return manifest


def run(root, output, seeds):
    output.mkdir(parents=True, exist_ok=True)
    dependencies = [Path('agent2/world_v5_dev.py'), Path('agent2/runtime_v5.py'), Path('agent2/world_v4.py'),
        Path('agent2/world_v4_schemes.py'), Path('agent2/world_v3.py'), Path('agent2/accounting_ext.py'),
        Path('agent2/validate_v4.py'), *sorted(Path('sme_fraud').glob('*.py'))]
    source_hashes = {str(p): sha256(p) for p in dependencies}
    plan = {'data_origin': 'dữ liệu tổng hợp', 'worlds': [development_config(s) for s in seeds], 'source_hashes': source_hashes,
            'validation': 'V1-V12; V10 scheme coverage reported explicitly, not silently passed', 'memory_cap_gib': 6}
    plan_path = output / 'generation_plan.json'
    if plan_path.exists() and json.loads(plan_path.read_text(encoding='utf-8')) != plan:
        raise ValueError('Generation plan or source hashes changed; refuse mixed world versions')
    write_json(plan_path, plan)
    for seed in seeds:
        checkpoint = output / f'world_{seed}.json'
        directory = root / f'v5dev_s{seed}'
        if checkpoint.exists():
            previous = json.loads(checkpoint.read_text(encoding='utf-8'))
            if previous['status'] == 'validated':
                assert all(sha256(directory / name) == digest for name, digest in previous['file_hashes'].items())
                continue
        wait_memory(3, output / 'runtime.json')
        start = time.monotonic()
        write_json(output / 'runtime.json', {'status':'generating', 'seed':seed,'data_origin':'dữ liệu tổng hợp'})
        if not (directory / 'manifest.json').exists():
            generate(development_config(seed), directory)
        report = validate_v4(directory, run_shortcut=True)
        checks = {f'V{i}': 'passed' for i in range(1, 13)}
        checks['V10'] = 'coverage_gaps_reported' if report['scheme_split_gaps'] else 'passed'
        if report['scheme_split_gaps']:
            write_json(checkpoint, {'status':'validation_failed','data_origin':'dữ liệu tổng hợp',
                       'seed':seed,'checks':checks,'validation':report})
            raise ValueError(f'V10 coverage incomplete in development seed {seed}; no detector may run')
        result = {'status': 'validated', 'data_origin':'dữ liệu tổng hợp', 'seed':seed,
                  'seconds':time.monotonic()-start, 'config':development_config(seed), 'checks':checks,
                  'validation':report, 'file_hashes':{p.name:sha256(p) for p in sorted(directory.glob('*.csv'))}}
        write_json(checkpoint, result)
        print(f'validated development seed {seed}: {result["seconds"]:.1f}s; V10={checks["V10"]}', flush=True)
        gc.collect()
    write_json(output / 'runtime.json', {'status':'complete','worlds':len(seeds),'data_origin':'dữ liệu tổng hợp'})


def main():
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument('--root', type=Path, default=Path('work/data'))
    p.add_argument('--output', type=Path, default=Path('results/v5/development'))
    p.add_argument('--seeds', type=int, nargs='+', default=list(range(1001,1021)))
    args=p.parse_args()
    limit_memory(6)
    try:
        run(args.root,args.output,args.seeds)
    except Exception as error:
        write_json(args.output / 'failure.json', {'status':'failed','error':repr(error),'data_origin':'dữ liệu tổng hợp'})
        raise


if __name__ == '__main__':
    main()
